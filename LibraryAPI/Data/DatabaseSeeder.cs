        public static void Seed(LibraryContext db, IPasswordHasher hasher, ILogger logger)
        {
            SeedAccounts(db, hasher, logger);
            SeedCatalog(db, logger);
        }
        private static void SeedAccounts(LibraryContext db, IPasswordHasher hasher, ILogger logger)
        {
            // Seed Admin
            if (!db.Accounts.Any(a => a.role == "admin"))
            {
                db.Accounts.Add(new Account
                {
                    login = "admin",
                    passwordHash = hasher.Hash("admin123"),
                    role = "admin"
                });
                logger.LogInformation("Seeded admin account");
            }

            // Seed Librarian
            if (!db.Accounts.Any(a => a.role == "librarian"))
            {
                db.Accounts.Add(new Account
                {
                    login = "librarian",
                    passwordHash = hasher.Hash("librarian123"),
                    role = "librarian"
                });
                logger.LogInformation("Seeded librarian account");
            }

            db.SaveChanges();
        }

        private static void SeedCatalog(LibraryContext db, ILogger logger)
        {

            if (db.Authors.Any()) return;

            var authors = new List<Author>(Catalog.Length);

            foreach (var (name, country, bookEntries) in Catalog)
            {
                var author = new Author { name = name, country = country };

                foreach (var entry in bookEntries)
                {
                    var separator = entry.LastIndexOf('|');
                    var title = entry[..separator];
                    var year = int.Parse(entry[(separator + 1)..]);

                    author.books.Add(new Book { title = title, year = year });
                }

                authors.Add(author);
            }

            db.Authors.AddRange(authors);
            db.SaveChanges();

            var totalBooks = authors.Sum(author => author.books.Count);
            logger.LogInformation("Seeded {Authors} authors and {Books} books", authors.Count, totalBooks);
        }

